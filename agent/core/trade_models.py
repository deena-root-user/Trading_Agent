@dataclass
class PipelineContext:
    """
    Full market context passed to all pipeline stages.
    Immutable snapshot — no stage should modify this.
    """
    symbol: str = ""
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    # Prices
    bid: float = 0.0
    ask: float = 0.0
    spread_pips: float = 0.0

    # SMC snapshots
    smc_4h: Dict[str, Any] = field(default_factory=dict)
    smc_1h: Dict[str, Any] = field(default_factory=dict)
    smc_15m: Dict[str, Any] = field(default_factory=dict)
    smc_1m: Dict[str, Any] = field(default_factory=dict)

    # Indicators
    indicators_4h: Optional[Any] = None
    indicators_1h: Optional[Any] = None
    indicators_15m: Optional[Any] = None
    indicators_1m: Optional[Any] = None

    # Session
    session: str = "UNKNOWN"
    is_kill_zone: bool = False
    session_dict: Dict[str, Any] = field(default_factory=dict)

    # Regime
    regime: str = "UNKNOWN"
    regime_confidence: float = 0.0
    regime_features: Dict[str, Any] = field(default_factory=dict)

    # Account state
    account_balance: float = 0.0
    account_equity: float = 0.0
    daily_pnl_usd: float = 0.0
    open_positions: List[dict] = field(default_factory=list)
    consecutive_losses: int = 0

    # News
    news_blocked: bool = False
    news_reason: str = ""

    # ATR reference (most useful timeframe)
    atr_1h: float = 1.0
    atr_15m: float = 0.5

    @property
    def mid_price(self) -> float:
        return (self.bid + self.ask) / 2.0

    @property
    def open_positions_count(self) -> int:
        return len(self.open_positions)

    def to_features_dict(self) -> dict:
        """For traceability — full snapshot of context."""
        return {
            "symbol": self.symbol,
            "timestamp": self.timestamp.isoformat(),
            "bid": self.bid,
            "ask": self.ask,
            "spread_pips": self.spread_pips,
            "session": self.session,
            "is_kill_zone": self.is_kill_zone,
            "regime": self.regime,
            "regime_confidence": self.regime_confidence,
            "account_balance": self.account_balance,
            "daily_pnl_usd": self.daily_pnl_usd,
            "open_positions_count": self.open_positions_count,
            "news_blocked": self.news_blocked,
            "atr_1h": self.atr_1h,
            "trend_4h": self.smc_4h.get("trend", "NEUTRAL"),
            "trend_1h": self.smc_1h.get("trend", "NEUTRAL"),
            "trend_15m": self.smc_15m.get("trend", "NEUTRAL"),
        }
