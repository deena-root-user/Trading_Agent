"""
PAXIS Agent — Canonical Trade Objects
======================================
Defines the authoritative data contracts for the entire pipeline.

Every trade MUST flow through these typed objects:
  TradeCandidate  → generated by strategy (NO volume)
  ApprovedTrade   → approved by Risk Engine (WITH volume)
  TradeLeg        → individual partial-exit segment
  TradeLifecycleState → explicit state machine

No strategy may execute an order without an ApprovedTrade existing.
No ApprovedTrade may exist without passing through the Risk Engine.

Architecture:
  Strategy → TradeCandidate → Risk Engine → ApprovedTrade → ExecutionAuthority → MT5
"""
from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional


# ══════════════════════════════════════════════════════════════════════════════
# ENUMS
# ══════════════════════════════════════════════════════════════════════════════


class TradeLifecycleState(Enum):
    """Full state machine for every trade, from signal to exit."""
    MARKET_DATA       = "MARKET_DATA"
    SETUP_DETECTED    = "SETUP_DETECTED"
    CANDIDATE         = "CANDIDATE"
    QUALITY_CHECK     = "QUALITY_CHECK"
    RISK_CHECK        = "RISK_CHECK"
    APPROVED          = "APPROVED"
    EXECUTION_PENDING = "EXECUTION_PENDING"
    EXECUTED          = "EXECUTED"
    MANAGED           = "MANAGED"
    PARTIAL_EXIT      = "PARTIAL_EXIT"
    CLOSED            = "CLOSED"
    REJECTED          = "REJECTED"
    CANCELLED         = "CANCELLED"


class EntryMode(Enum):
    """Which entry mode produced this trade candidate."""
    STRUCTURAL     = "STRUCTURAL"    # Retracement into POI
    BREAKOUT       = "BREAKOUT"      # Confirmed BOS + displacement
    AUTO_SCALP     = "AUTO_SCALP"    # Short-term scalp
    BREAKOUT_RETEST = "BREAKOUT_RETEST"  # Breakout + micro-retest


class Direction(Enum):
    BUY  = "BUY"
    SELL = "SELL"


class StrategyFamily(Enum):
    SMC           = "SMC"
    ICT           = "ICT"
    AUTO_SCALP    = "AUTO_SCALP"
    BREAKOUT      = "BREAKOUT"


# ══════════════════════════════════════════════════════════════════════════════
# TRADE CANDIDATE
# ══════════════════════════════════════════════════════════════════════════════


@dataclass
class TradeCandidate:
    """
    Output of the strategy layer. Contains setup metadata but NO volume.
    Volume is determined exclusively by the Risk Engine.

    IMPORTANT: A strategy must NEVER set volume/lot_size.
    That responsibility belongs to the Risk Engine.
    """
    # Identity
    signal_id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    symbol: str = ""
    direction: str = "BUY"           # "BUY" | "SELL"
    strategy: str = ""               # e.g. "SMC_OB_PULLBACK"
    strategy_family: str = "SMC"     # StrategyFamily value
    strategy_version: str = "1.0"
    entry_mode: str = "STRUCTURAL"   # EntryMode value

    # Timestamp
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    # Price levels (NO volume here)
    entry: float = 0.0
    stop_loss: float = 0.0
    tp1: Optional[float] = None
    tp2: Optional[float] = None
    tp3: Optional[float] = None

    # Quality scores
    setup_score: float = 0.0
    confluence_score: float = 0.0
    quality_grade: str = "NO_GRADE"  # "A+", "A", "B", "C", "REJECT"

    # Context
    regime: str = "UNKNOWN"
    session: str = "UNKNOWN"
    is_kill_zone: bool = False
    spread_pips: float = 0.0

    # Breakout-specific
    bos_confirmed: bool = False
    displacement_confirmed: bool = False
    displacement_atr_ratio: float = 0.0
    structure_id: Optional[str] = None  # Prevents duplicate entries on same BOS

    # Full traceability snapshot
    signal_features: Dict[str, Any] = field(default_factory=dict)
    regime_features: Dict[str, Any] = field(default_factory=dict)

    # Derived
    @property
    def rr_ratio(self) -> float:
        if not self.tp1 or self.entry <= 0 or self.stop_loss <= 0:
            return 0.0
        sl_dist = abs(self.entry - self.stop_loss)
        tp_dist = abs(self.tp1 - self.entry)
        return round(tp_dist / sl_dist, 2) if sl_dist > 0 else 0.0

    @property
    def sl_distance(self) -> float:
        return abs(self.entry - self.stop_loss)

    def is_valid(self) -> bool:
        """Basic structural validity check."""
        if self.entry <= 0 or self.stop_loss <= 0:
            return False
        if self.direction == "BUY" and self.stop_loss >= self.entry:
            return False
        if self.direction == "SELL" and self.stop_loss <= self.entry:
            return False
        if self.tp1 is not None:
            if self.direction == "BUY" and self.tp1 <= self.entry:
                return False
            if self.direction == "SELL" and self.tp1 >= self.entry:
                return False
        return True

    def to_dict(self) -> dict:
        return {
            "signal_id": self.signal_id,
            "symbol": self.symbol,
            "direction": self.direction,
            "strategy": self.strategy,
            "strategy_family": self.strategy_family,
            "entry_mode": self.entry_mode,
            "timestamp": self.timestamp.isoformat(),
            "entry": self.entry,
            "stop_loss": self.stop_loss,
            "tp1": self.tp1,
            "tp2": self.tp2,
            "tp3": self.tp3,
            "rr_ratio": self.rr_ratio,
            "setup_score": self.setup_score,
            "confluence_score": self.confluence_score,
            "quality_grade": self.quality_grade,
            "regime": self.regime,
            "session": self.session,
            "is_kill_zone": self.is_kill_zone,
            "spread_pips": self.spread_pips,
            "bos_confirmed": self.bos_confirmed,
            "displacement_confirmed": self.displacement_confirmed,
        }


