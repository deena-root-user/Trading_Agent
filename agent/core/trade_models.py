@dataclass
class TradeLeg:
    """
    One partial-exit segment of a position.
    Each leg books PnL IMMEDIATELY when it closes.

    Example:
        Trade #1001 — BUY XAUUSD 0.02 lots
        Leg 1: 0.01 lots closed at TP1 → PnL booked immediately
        Leg 2: 0.01 lots closed at SL  → PnL booked immediately
        Total trade PnL = Leg1.pnl_usd + Leg2.pnl_usd
    """
    leg_id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    parent_signal_id: str = ""
    symbol: str = ""
    direction: str = "BUY"

    entry_price: float = 0.0
    exit_price: float = 0.0
    volume: float = 0.0
    lot_fraction: float = 1.0   # e.g. 0.5 for 50% of position

    entry_time: Optional[datetime] = None
    exit_time: Optional[datetime] = None

    pnl_usd: float = 0.0
    pnl_r: float = 0.0
    exit_reason: str = ""  # "TP1", "TP2", "SL", "BREAKEVEN", "TRAILING", "MANUAL", "TIMEOUT"

    commission_usd: float = 0.0
    spread_cost_usd: float = 0.0
    swap_usd: float = 0.0

    @property
    def net_pnl_usd(self) -> float:
        return self.pnl_usd - self.commission_usd - self.spread_cost_usd - abs(self.swap_usd)

    @property
    def holding_seconds(self) -> Optional[float]:
        if self.entry_time and self.exit_time:
            return (self.exit_time - self.entry_time).total_seconds()
        return None


