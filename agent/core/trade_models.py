# APPROVED TRADE
# ══════════════════════════════════════════════════════════════════════════════


@dataclass
class ApprovedTrade:
    """
    Output of the Risk Engine. The ONLY object that permits MT5 execution.
    ExecutionAuthority checks isinstance(x, ApprovedTrade) before placing orders.

    Contains the original candidate PLUS broker-aware sizing.
    """
    candidate: TradeCandidate

    # Risk Engine outputs
    volume: float = 0.0
    allowed_risk_usd: float = 0.0
    actual_risk_usd: float = 0.0
    margin_required: Optional[float] = None

    # Broker constraints used
    broker_volume_step: float = 0.01
    broker_min_volume: float = 0.01
    broker_max_volume: float = 100.0
    broker_stops_level: int = 0

    # Risk calculation detail
    risk_pct: float = 0.0
    sl_distance_points: float = 0.0
    tick_value: float = 0.0
    contract_size: float = 0.0

    # Approval state
    risk_approved: bool = False
    rejection_reason: Optional[str] = None
    rejection_codes: List[str] = field(default_factory=list)

    # Environment that approved this
    environment: str = "PAPER"  # "DEVELOPMENT" | "PAPER" | "LIVE"

    # Versions at time of approval
    risk_engine_version: str = "2.0"
    config_hash: str = ""

    @property
    def signal_id(self) -> str:
        return self.candidate.signal_id

    @property
    def symbol(self) -> str:
        return self.candidate.symbol

    @property
    def direction(self) -> str:
        return self.candidate.direction

    @property
    def entry(self) -> float:
        return self.candidate.entry

    @property
    def stop_loss(self) -> float:
        return self.candidate.stop_loss

    @property
    def tp1(self) -> Optional[float]:
        return self.candidate.tp1

    @property
    def tp2(self) -> Optional[float]:
        return self.candidate.tp2

    def is_executable(self) -> bool:
        """Returns True only if this trade may proceed to MT5."""
        return (
            self.risk_approved
            and self.volume > 0
            and self.volume >= self.broker_min_volume
            and self.volume <= self.broker_max_volume
            and self.candidate.is_valid()
        )

    def to_dict(self) -> dict:
        d = self.candidate.to_dict()
        d.update({
            "volume": self.volume,
            "allowed_risk_usd": round(self.allowed_risk_usd, 4),
            "actual_risk_usd": round(self.actual_risk_usd, 4),
            "risk_pct": round(self.risk_pct, 4),
            "margin_required": self.margin_required,
            "broker_volume_step": self.broker_volume_step,
            "broker_min_volume": self.broker_min_volume,
            "risk_approved": self.risk_approved,
            "rejection_reason": self.rejection_reason,
            "rejection_codes": self.rejection_codes,
            "environment": self.environment,
            "risk_engine_version": self.risk_engine_version,
        })
        return d


